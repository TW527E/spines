/**
 * Prepares the gallery for the web. Every PNG under `art/<group>/` becomes a
 * small WebP the Worker can inline into a shelf, and a manifest records each
 * print's title, group and size so shelves are laid out without decoding.
 * It also rewrites `art/WANTED.md`, the catalog entries still waiting for a
 * print. The rules a print must meet are in `art/README.md`.
 *
 *   pnpm art
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { preset, presets } from '../src/presets.ts'

const root = fileURLToPath(new URL('../../../', import.meta.url))
const source = join(root, 'art')
const target = join(root, 'apps/web/public/art')
const HEIGHT = 720

rmSync(target, { recursive: true, force: true })
mkdirSync(target, { recursive: true })

const manifest: Record<string, { title: string; group: string; width: number; height: number }> = {}
const problems: string[] = []

const groups = readdirSync(source, { withFileTypes: true }).filter((d) => d.isDirectory())
for (const { name: group } of groups.sort((a, b) => a.name.localeCompare(b.name))) {
  for (const file of readdirSync(join(source, group)).sort()) {
    if (!file.endsWith('.png')) continue
    const name = basename(file, '.png')
    const slug = name.toLowerCase().replaceAll('_', '-')
    const where = `art/${group}/${file}`

    if (!/^[a-z0-9][a-z0-9.-]*$/.test(slug))
      problems.push(`${where}: use letters, digits, '.', '-' or '_'`)
    if (manifest[slug])
      problems.push(`${where}: slug "${slug}" is taken by art/${manifest[slug].group}`)

    const image = sharp(join(source, group, file))
    const meta = await image.metadata()
    if (!meta.width || !meta.height || meta.width >= meta.height) {
      problems.push(`${where}: a print must stand upright (taller than wide)`)
      continue
    }
    if (meta.height < HEIGHT)
      problems.push(`${where}: ${meta.height}px tall, at least ${HEIGHT}px needed`)

    const { width, height } = await image
      .resize({ height: HEIGHT })
      .webp({ quality: 84 })
      .toFile(join(target, `${slug}.webp`))
    const entry = preset(slug)
    if (entry && entry.slug !== slug)
      problems.push(`${where}: name it ${entry.slug}.png, the catalog's slug`)
    if (entry && entry.group !== group)
      problems.push(`${where}: ${slug} belongs in art/${entry.group}/`)
    manifest[slug] = { title: entry?.title ?? name.replaceAll('_', ' '), group, width, height }
  }
}

if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}

const wanted = (group: string) =>
  presets
    .filter((p) => p.group === group && !manifest[p.slug])
    .map((p) => `- [ ] \`art/${group}/${p.slug}.png\` — ${p.title}`)
    .join('\n')

writeFileSync(
  join(source, 'WANTED.md'),
  `# Wanted prints

Catalog entries that are still typeset because nobody has drawn their print yet.
One image per entry; see [README.md](README.md) for how. Generated by \`pnpm art\`.

## AI tools

${wanted('ai')}

## Tech stack

${wanted('stack')}

## Games & VR

${wanted('games')}
`.replace(/\s*$/, '\n'),
)

writeFileSync(
  join(root, 'apps/web/src/art.generated.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
)
console.log(`${Object.keys(manifest).length} prints → apps/web/public/art`)
